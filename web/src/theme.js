// The editor's colours: the surroundings are PyMagic's (colours of look.css, the violet of the icon, a golden spark for what is searched
// for); the code is coloured as VS Code colours it (Dark Modern and Light Modern, the Dark+ and Light+ colours), or with PyMagic's own
// palette when the person chooses it in Settings (codeColors).
export const THEME = 'pymagic';
export const THEME_LIGHT = 'pymagic-light';
export const THEME_VSCODE = 'pymagic-vscode';
export const THEME_VSCODE_LIGHT = 'pymagic-vscode-light';
/** Monaco's theme for each choice of code colours and each of dark and light. */
export const THEMES = { vscode: { dark: THEME_VSCODE, light: THEME_VSCODE_LIGHT }, pymagic: { dark: THEME, light: THEME_LIGHT } };

/** The theme for a choice of code colours ('vscode', the default, or 'pymagic') and 'dark' or 'light'. */
export function themeName(codeColors, theme) {
    return (THEMES[codeColors] ?? THEMES.vscode)[theme === 'light' ? 'light' : 'dark'];
}

