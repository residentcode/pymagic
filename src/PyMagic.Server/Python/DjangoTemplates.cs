    /// <summary>A secret key as Django makes one (get_random_secret_key): "django-insecure-" and 50 characters of its alphabet.</summary>
    public static string SecretKey()
    {
        const string chars = "abcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*(-_=+)";
        var sb = new StringBuilder("django-insecure-");
        for (int i = 0; i < 50; i++) sb.Append(chars[RandomNumberGenerator.GetInt32(chars.Length)]);
        return sb.ToString();
    }

    /// <summary>The class name of an app's config as startapp writes it: "blog_posts" gives "BlogPosts" (Python's str.title(), underscores dropped).</summary>
    public static string CamelCase(string app)
    {
        var sb = new StringBuilder();
        bool start = true;
        foreach (char c in app)
        {
            if (char.IsLetter(c)) { sb.Append(start ? char.ToUpperInvariant(c) : char.ToLowerInvariant(c)); start = false; }
            else { if (c != '_') sb.Append(c); start = true; }
        }
        return sb.ToString();
    }

    /// <summary>Django's own files of a project (and of an app, when one is named), as startproject and startapp write them with the templates above.</summary>
    public static Dictionary<string, string> Builtin(string module, string? app, string version = Version, string? secret = null)
    {
        // the text as Django writes it, with \n line endings whatever this file was saved with
        string Fill(string t) => t.Replace("\r\n", "\n").Replace("{{ project_name }}", module).Replace("{{ django_version }}", version).Replace("{{ docs_version }}", DocsVersion(version))
            .Replace("{{ secret_key }}", secret ?? SecretKey());
        var files = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["manage.py"] = Fill(Manage),
            [module + "/__init__.py"] = "",
            [module + "/settings.py"] = Fill(Settings),
            [module + "/urls.py"] = Fill(Urls),
            [module + "/wsgi.py"] = Fill(Wsgi),
            [module + "/asgi.py"] = Fill(Asgi),
        };
        if (app != null)
        {
            files[app + "/__init__.py"] = "";
            files[app + "/admin.py"] = "from django.contrib import admin\n\n# Register your models here.\n";
            files[app + "/apps.py"] = AppConfig.Replace("\r\n", "\n").Replace("{{ camel_case_app_name }}", CamelCase(app)).Replace("{{ app_name }}", app);
            files[app + "/models.py"] = "from django.db import models\n\n# Create your models here.\n";
            files[app + "/views.py"] = "from django.shortcuts import render\n\n# Create your views here.\n";
            files[app + "/tests.py"] = "from django.test import TestCase\n\n# Create your tests here.\n";
            files[app + "/migrations/__init__.py"] = "";
        }
        return files;
    }

    /// <summary>
    /// The choices of New Project made in Django's files (of any version, quoted as that Django writes them): the templates folder in DIRS, or Jinja2
    /// reading it before Django's engine; the app in INSTALLED_APPS; without the admin, its app, its URL and the app's admin.py left out.
    /// </summary>
    public static void Apply(Dictionary<string, string> files, string module, string? app, string folder, bool jinja, bool admin)
    {
        string settingsPath = module + "/settings.py", urlsPath = module + "/urls.py";
        if (!files.TryGetValue(settingsPath, out var settings)) return;
        char q = settings.Contains("\"BACKEND\"") ? '"' : '\'';
        string Q(string s) => q + s + q;
        if (jinja)
        {
            // Jinja2 reads the project's templates; Django's own engine stays for the admin and the apps' templates
            string backend = $"    {{\n        {Q("BACKEND")}: {Q("django.template.backends.jinja2.Jinja2")},\n        {Q("DIRS")}: [BASE_DIR / {Q(folder)}],\n        {Q("APP_DIRS")}: True,\n        {Q("OPTIONS")}: {{}},\n    }},\n";
            settings = Regex.Replace(settings, @"TEMPLATES = \[\n", m => m.Value + backend, RegexOptions.None, TimeSpan.FromSeconds(1));
        }
        else
            settings = Regex.Replace(settings, @"(['""])DIRS\1:\s*\[\]", m => $"{m.Groups[1].Value}DIRS{m.Groups[1].Value}: [BASE_DIR / {Q(folder)}]");
        if (app != null)
            settings = Regex.Replace(settings, @"(INSTALLED_APPS = \[\n(?:[ \t]+.*\n)*?)\]", m => m.Groups[1].Value + "    " + Q(app) + ",\n]");
        if (!admin)
        {
            settings = Regex.Replace(settings, @"[ \t]+['""]django\.contrib\.admin['""],\n", "");
            if (files.TryGetValue(urlsPath, out var urls))
                files[urlsPath] = Regex.Replace(Regex.Replace(urls, @"from django\.contrib import admin\n", ""), @"[ \t]+path\(['""]admin/['""], admin\.site\.urls\),\n", "");
            if (app != null) files.Remove(app + "/admin.py");
        }
        files[settingsPath] = settings;
    }

    /// <summary>The Django version of an interpreter ("5.2.8"), or null when it has none (or does not answer).</summary>
    public static string? VersionOf(string python)
    {
        var (code, output) = RunOut(python, Path.GetTempPath(), "-c", "import django; print(django.get_version())");
        return code == 0 && Regex.IsMatch(output.Trim(), @"^\d+\.\d+") ? output.Trim() : null;
    }

    /// <summary>
    /// What an interpreter's own Django writes: <c>startproject</c> of the project (and <c>startapp</c> of the app) in a folder of its own, read back
    /// by path. The folder is removed afterwards.
    /// </summary>
    public static Dictionary<string, string> FromDjango(string python, string module, string? app)
    {
        string temp = Path.Combine(Path.GetTempPath(), "pm_django_" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(temp);
        try
        {
            var (code, output) = RunOut(python, temp, "-m", "django", "startproject", module, temp);
            if (code != 0) throw new ServiceException("django-admin startproject failed: " + Last(output));
            if (app != null)
            {
                (code, output) = RunOut(python, temp, "-m", "django", "startapp", app);
                if (code != 0) throw new ServiceException("django-admin startapp failed: " + Last(output));
            }
            var files = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var file in Directory.EnumerateFiles(temp, "*", SearchOption.AllDirectories))
            {
                string rel = Path.GetRelativePath(temp, file).Replace('\\', '/');
                if (rel.Contains("__pycache__")) continue;
                files[rel] = File.ReadAllText(file).Replace("\r\n", "\n");
            }
            return files;
        }
        finally { try { Directory.Delete(temp, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }
    }

    static string Last(string text) => text.Trim().Split('\n').LastOrDefault()?.Trim() ?? "";

    static (int Code, string Output) RunOut(string program, string folder, params string[] args)
    {
        var psi = new ProcessStartInfo(program) { WorkingDirectory = folder, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, CreateNoWindow = true };
        foreach (var a in args) psi.ArgumentList.Add(a);
        psi.Environment["PYTHONIOENCODING"] = "utf-8";
        try
        {
            using var p = Process.Start(psi);
            if (p == null) return (-1, "cannot start " + program);
            var err = p.StandardError.ReadToEndAsync();
            string output = p.StandardOutput.ReadToEnd();
            if (!p.WaitForExit(120000)) { try { p.Kill(true); } catch (InvalidOperationException) { } return (-1, program + " took too long"); }
            return (p.ExitCode, p.ExitCode == 0 ? output : err.Result + output);
        }
        catch (System.ComponentModel.Win32Exception e) { return (-1, e.Message); }
    }
