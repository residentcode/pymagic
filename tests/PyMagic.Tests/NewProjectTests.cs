    /// <summary>
    /// A Django project in a new environment: Django is installed there and its own startproject writes the project (a download from PyPI: only with
    /// PYMAGIC_TEST_DJANGO_INSTALL=1 and PYMAGIC_TEST_PYTHON naming the Python the .venv is made with); without installing, Django's own template.
    /// </summary>
    [Fact]
    public void ADjangoProjectInANewEnvironmentIsWrittenByTheDjangoInstalledThere()
    {
        string? python = Environment.GetEnvironmentVariable("PYMAGIC_TEST_PYTHON");
        if (python is not { Length: > 0 } || !File.Exists(python)) return;
        // installing left out: the .venv is made, the files are Django's own template, and the note says why
        string folder = TempFolder();
        try
        {
            var made = NewProject.Create(new NewProjectRequest(folder, "django", false, false, "venv", python, null, null, new DjangoProjectOptions(AppName: "blog"), InstallPackages: false));
            Assert.True(File.Exists(made.Interpreter!));
            string settings = File.ReadAllText(Path.Combine(folder, "my_site", "settings.py"));
            Assert.True(settings.Contains($"using Django {DjangoTemplates.Version}.") && settings.Contains("    'blog',\n]"), settings);
            Assert.True(made.Notes.Any((n) => n.Contains("requirements.txt")), string.Join(" | ", made.Notes));
        }
        finally { try { Directory.Delete(Path.GetDirectoryName(folder)!, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }

        if (Environment.GetEnvironmentVariable("PYMAGIC_TEST_DJANGO_INSTALL") != "1") return;
        folder = TempFolder();
        try
        {
            var made = NewProject.Create(new NewProjectRequest(folder, "django", false, false, "venv", python, null, null, new DjangoProjectOptions("django", "templates", "blog", Admin: false)));
            string version = DjangoTemplates.VersionOf(made.Interpreter!) ?? throw new AssertionException("Django was not installed: " + string.Join(" | ", made.Notes));
            Assert.True(made.Notes.Any((n) => n.Contains($"Django {version} was installed")), string.Join(" | ", made.Notes));
            string settings = File.ReadAllText(Path.Combine(folder, "my_site", "settings.py"));
            Assert.True(settings.Contains($"Generated by 'django-admin startproject' using Django {version}."), settings);
            Assert.True(settings.Contains("'DIRS': [BASE_DIR / 'templates']") && settings.Contains("    'blog',\n]") && !settings.Contains("django.contrib.admin"), settings);
            Assert.True(!File.Exists(Path.Combine(folder, "blog", "admin.py")));
            // and Django's own check passes on it
            var psi = new ProcessStartInfo(made.Interpreter!) { WorkingDirectory = folder, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, CreateNoWindow = true };
            psi.ArgumentList.Add("manage.py");
            psi.ArgumentList.Add("check");
            using var p = Process.Start(psi)!;
            string output = p.StandardOutput.ReadToEnd() + p.StandardError.ReadToEnd();
            p.WaitForExit(60000);
            Assert.True(p.ExitCode == 0 && output.Contains("no issues"), output);
        }
        finally { try { Directory.Delete(Path.GetDirectoryName(folder)!, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }
    }

    [Fact]
    public void ADjangoProjectWithItsTemplateLanguageFolderFirstAppAndAdmin()
    {
        var files = NewProject.Files("django", "Shop", true, new DjangoProjectOptions("jinja2", "site/tpl", "Blog Posts", Admin: false));
        Assert.Equal("blog_posts/__init__.py,blog_posts/apps.py,blog_posts/migrations/__init__.py,blog_posts/models.py,blog_posts/tests.py,blog_posts/views.py,manage.py,requirements.txt," +
            "shop/__init__.py,shop/asgi.py,shop/settings.py,shop/urls.py,shop/wsgi.py,site/tpl/.gitkeep", string.Join(",", files.Keys.OrderBy(k => k, StringComparer.Ordinal)));
        string settings = files["shop/settings.py"];
        Assert.True(settings.Contains("'BACKEND': 'django.template.backends.jinja2.Jinja2',\n        'DIRS': [BASE_DIR / 'site/tpl']"), settings);
        Assert.True(settings.Contains("django.template.backends.django.DjangoTemplates',\n        'DIRS': []"));
        Assert.True(!settings.Contains("django.contrib.admin") && settings.Contains("    'blog_posts',\n]"));
        Assert.True(!files["shop/urls.py"].Contains("admin"));
        Assert.True(files["blog_posts/apps.py"].Contains("class BlogPostsConfig(AppConfig):"));
        Assert.Equal("django\njinja2\n", files["requirements.txt"]);
        // the defaults are what startproject makes, with the admin
        var plain = NewProject.Files("django", "Shop", true);
        Assert.True(plain["shop/settings.py"].Contains("'django.contrib.admin'") && plain["shop/urls.py"].Contains("admin.site.urls") && plain.ContainsKey("templates/.gitkeep"));
        Assert.True(plain["shop/settings.py"].Contains("'DIRS': [BASE_DIR / 'templates']"), plain["shop/settings.py"]);
        try { NewProject.Files("django", "shop", true, new DjangoProjectOptions(AppName: "shop")); throw new AssertionException("no error"); }
        catch (ServiceException) { }
        foreach (var (path, text) in files)
            if (path.EndsWith(".py")) Assert.Equal(0, Parser.Parse(text).Diagnostics.Count);

        // with Django on the computer, Django's own check passes on what was made
        if (Environment.GetEnvironmentVariable("PYMAGIC_TEST_DJANGO") is not { Length: > 0 } python) return;
        string folder = TempFolder();
        try
        {
            NewProject.Create(new NewProjectRequest(folder, "django", false, false, "none", null, null, null, new DjangoProjectOptions("django", "templates", "blog", Admin: false)));
            var psi = new ProcessStartInfo(python) { WorkingDirectory = folder, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, CreateNoWindow = true };
            psi.ArgumentList.Add("manage.py");
            psi.ArgumentList.Add("check");
            using var p = Process.Start(psi)!;
            string output = p.StandardOutput.ReadToEnd() + p.StandardError.ReadToEnd();
            p.WaitForExit(60000);
            Assert.True(p.ExitCode == 0 && output.Contains("no issues"), output);
        }
        finally { try { Directory.Delete(Path.GetDirectoryName(folder)!, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }

        // an interpreter that has Django: the project is what that Django's own startproject writes, with the choices made in it
        string version = DjangoTemplates.VersionOf(python) ?? throw new AssertionException("PYMAGIC_TEST_DJANGO has no Django");

        // PyMagic's own copy of the templates is Django's, file for file (only the random secret key differs), when that Django is the same release line
        if (DjangoTemplates.DocsVersion(version) == DjangoTemplates.DocsVersion(DjangoTemplates.Version))
        {
            var real = DjangoTemplates.FromDjango(python, "my_site", "blog");
            var ours = DjangoTemplates.Builtin("my_site", "blog", version);
            static string NoSecret(string text) => System.Text.RegularExpressions.Regex.Replace(text, @"SECRET_KEY = '[^']*'", "SECRET_KEY = '…'");
            Assert.Equal(string.Join(",", real.Keys.OrderBy(k => k, StringComparer.Ordinal)), string.Join(",", ours.Keys.OrderBy(k => k, StringComparer.Ordinal)));
            foreach (var (path, text) in real) Assert.Equal(NoSecret(text), NoSecret(ours[path]));
        }
        string own = TempFolder();
        try
        {
            NewProject.Create(new NewProjectRequest(own, "django", false, false, "interpreter", python, null, null, new DjangoProjectOptions("django", "templates", "blog", Admin: true)));
            string made = File.ReadAllText(Path.Combine(own, NewProject.ModuleName(Path.GetFileName(own)), "settings.py"));
            Assert.True(made.Contains($"Generated by 'django-admin startproject' using Django {version}."), made);
            Assert.True(made.Contains("'blog',\n]") || made.Contains("\"blog\",\n]"), made);
            Assert.True(File.Exists(Path.Combine(own, "blog", "apps.py")) && File.Exists(Path.Combine(own, "blog", "admin.py")));
        }
        finally { try { Directory.Delete(Path.GetDirectoryName(own)!, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }
    }

    [Fact]
    public void MakesTheFolderWithGitAndRefusesOneThatIsNotEmpty()
    {
        string folder = TempFolder();
        try
        {
            var r = NewProject.Create(new NewProjectRequest(folder, "flask", true, true, "none", null, null, null));
            Assert.Equal(".gitignore,app.py,requirements.txt,static/.gitkeep,templates/.gitkeep", string.Join(",", r.Files));
            Assert.True(File.Exists(Path.Combine(folder, "app.py")) && Directory.Exists(Path.Combine(folder, "templates")));
            Assert.True(Directory.Exists(Path.Combine(folder, ".git")), "git init ran");
            Assert.True(r.Interpreter == null);
            try { NewProject.Create(new NewProjectRequest(folder, "python", false, true, "none", null, null, null)); throw new AssertionException("no error"); }
            catch (ServiceException e) { Assert.Equal("The folder is not empty.", e.Message); }
            try { NewProject.Create(new NewProjectRequest("relative/path", "python", false, true, "none", null, null, null)); throw new AssertionException("no error"); }
            catch (ServiceException e) { Assert.True(e.Message.Contains("full path")); }
        }
        finally { try { Directory.Delete(Path.GetDirectoryName(folder)!, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }
    }

    [Fact]
    public void MakesAProjectVenvAndRemembersItsInterpreter()
    {
        string python = Environment.GetEnvironmentVariable("PYMAGIC_PYTHON") ?? "python";
        try { using var p = Process.Start(new ProcessStartInfo(python, "--version") { RedirectStandardOutput = true, UseShellExecute = false, CreateNoWindow = true }); if (p == null || !p.WaitForExit(20000) || p.ExitCode != 0) return; }
        catch (System.ComponentModel.Win32Exception) { return; }
        string? exe = null;
        try
        {
            using var w = Process.Start(new ProcessStartInfo(python, "-c \"import sys; print(sys.executable)\"") { RedirectStandardOutput = true, UseShellExecute = false, CreateNoWindow = true })!;
            exe = w.StandardOutput.ReadToEnd().Trim();
        }
        catch (System.ComponentModel.Win32Exception) { return; }
        string folder = TempFolder();
        try
        {
            var r = NewProject.Create(new NewProjectRequest(folder, "python", false, true, "venv", exe, null, null));
            Assert.True(r.Interpreter != null && File.Exists(r.Interpreter) && r.Interpreter.Contains(".venv"), r.Interpreter ?? "none");
            var settings = JsonNode.Parse(File.ReadAllText(Path.Combine(folder, ".pymagic", "settings.json")))!;
            Assert.Equal(r.Interpreter, settings["interpreter"]!.GetValue<string>());
        }
        finally { try { Directory.Delete(Path.GetDirectoryName(folder)!, true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }
    }
